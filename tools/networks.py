#!/usr/bin/env python3
"""The networks catalogue of the site, the app and the device page: site/networks.json.

A copy of catalog.json of VoxMesh/meshcore-local-networks (radio profiles of local MeshCore networks by city).
`update` fetches the current one, checks it and writes the copy and include/NetCatalog.h (the places and the profiles
the boards can tune to, for the network search of the firmware, src/NetFind.inc); `check` checks the copy and that the
header matches it (CI). The pages keep only profiles they can apply (web/index.html netFits, site/netpick.js), but a
malformed catalogue fails here.
"""
import argparse
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'site' / 'networks.json'
HEADER = ROOT / 'include' / 'NetCatalog.h'
URL = 'https://raw.githubusercontent.com/VoxMesh/meshcore-local-networks/main/catalog.json'


def problems(c):
    out = []
    if not isinstance(c, dict) or c.get('schema_version') != 2 or not isinstance(c.get('locations'), list):
        return ['schema_version 2 with a list of locations expected']
    if not isinstance(c.get('updated'), str):
        out.append('updated: date text expected')
    places, nets = set(), set()
    for l in c['locations']:
        lid = l.get('id')
        if not isinstance(lid, str) or lid in places:
            out.append(f'location id {lid!r}: missing or repeated')
        places.add(lid)
        if not isinstance(l.get('name'), str) or not all(isinstance(l.get(k), (int, float)) for k in ('lat', 'lon')):
            out.append(f'{lid}: name, lat and lon expected')
        for n in l.get('networks') or []:
            nid, r = n.get('id'), n.get('radio') or {}
            if not isinstance(nid, str) or nid in nets:
                out.append(f'network id {nid!r}: missing or repeated')
            nets.add(nid)
            if not (isinstance(r.get('frequency_hz'), int) and 150_000_000 <= r['frequency_hz'] <= 2_500_000_000
                    and isinstance(r.get('bandwidth_hz'), int) and 7_000 <= r['bandwidth_hz'] <= 500_000
                    and r.get('sf') in range(5, 13) and r.get('cr') in range(5, 9)):
                out.append(f'{nid}: radio out of range {r}')
            url = n.get('community_url')
            if url is not None and not (isinstance(url, str) and url.startswith(('https://', 'http://'))):
                out.append(f'{nid}: community_url must be http(s)')
            if n.get('path_hash_bytes') not in (None, 1, 2, 3):
                out.append(f"{nid}: path_hash_bytes must be 1, 2 or 3, not {n['path_hash_bytes']!r}")
    for l in c['locations']:
        if l.get('parent_id') is not None and l['parent_id'] not in places:
            out.append(f"{l.get('id')}: unknown parent_id {l['parent_id']}")
    return out


def fits(r):
    """A profile the boards can use (Config::valid): 863-870 MHz, BW 62.5/125/250/500 kHz, SF 7-12, CR 5-8."""
    return (863_000_000 <= r['frequency_hz'] <= 870_000_000 and r['bandwidth_hz'] in (62_500, 125_000, 250_000, 500_000)
            and 7 <= r['sf'] <= 12 and 5 <= r['cr'] <= 8)


def header(c):
    """include/NetCatalog.h: the places with a network the boards can use (and the territories above them), then
    those networks; coordinates in 1/100 degree (about 1 km), frequency in kHz, bandwidth as an index of 62.5/125/250/500 kHz."""
    locs = c['locations']
    used = {l['id'] for l in locs if any(fits(n['radio']) for n in l.get('networks') or [])}
    for l in locs:  # a territory above a place stays: its networks are those of the place too
        if l['id'] in used and l.get('parent_id'):
            used.add(l['parent_id'])
    places = [l for l in locs if l['id'] in used]
    index = {l['id']: i for i, l in enumerate(places)}
    assert len(places) < 255
    q = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
    out = ['// Generated by tools/networks.py from site/networks.json: do not edit. The network search of the firmware',
           '// (include/NetFind.h) tunes to these profiles; the pages read the full catalogue.',
           '#pragma once', '#include <stdint.h>', 'namespace netcat {',
           f'constexpr const char* Updated="{c["updated"]}";',
           '// parent: index of the territory around the place, 255 - none.',
           'struct Place {const char* name;int16_t lat,lon;uint8_t parent;};',
           '// bw: 62.5 kHz << bw; hash: path hash bytes of the network (path_hash_bytes), 0 - not given.',
           'struct Net {uint32_t khz:20,bw:2,sf:4,cr:4,hash:2;uint8_t place;};',
           'constexpr Place places[]={']
    for l in places:
        out.append(f' {{{q(l["name"])},{round(l["lat"] * 100)},{round(l["lon"] * 100)},{index.get(l.get("parent_id"), 255)}}},')
    out.append('};')
    out.append('constexpr Net nets[]={')
    for l in places:
        for n in l.get('networks') or []:
            r = n['radio']
            if fits(r):
                bw = (62_500, 125_000, 250_000, 500_000).index(r['bandwidth_hz'])
                out.append(f' {{{r["frequency_hz"] // 1000},{bw},{r["sf"]},{r["cr"]},{n.get("path_hash_bytes") or 0},{index[l["id"]]}}},')
    out += ['};', 'constexpr unsigned placeCount=sizeof places/sizeof places[0],netCount=sizeof nets/sizeof nets[0];', '}', '']
    return '\n'.join(out)


def main():
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    p.add_argument('action', choices=['update', 'check'])
    a = p.parse_args()
    if a.action == 'update':
        with urllib.request.urlopen(URL, timeout=30) as r:
            c = json.load(r)
    else:
        c = json.loads(TARGET.read_text())
    bad = problems(c)
    if bad:
        print('\n'.join(bad), file=sys.stderr)
        return 1
    if a.action == 'update':
        TARGET.write_text(json.dumps(c, ensure_ascii=False, indent=1) + '\n')
        HEADER.write_text(header(c))
    elif not HEADER.exists() or HEADER.read_text() != header(c):
        print(f'{HEADER.relative_to(ROOT)} does not match {TARGET.relative_to(ROOT)}: run tools/networks.py update', file=sys.stderr)
        return 1
    n = sum(len(l.get('networks') or []) for l in c['locations'])
    print(f"{TARGET.relative_to(ROOT)}: {c['updated']}, {len(c['locations'])} locations, {n} networks")
    return 0


if __name__ == '__main__':
    sys.exit(main())
