#!/usr/bin/env python3
"""Anti-aliased faces of the 320x240 screens (M9, T-Deck): include/AaFonts.h (tools/i18n.py generate).

Inter, rendered with hinting into 4-bit coverage per pixel. Each face is sized so its cap height (the digit
height for the digit face) matches the X11 bitmap face it replaces, so the layouts keep their baselines and
rows. Code points: ASCII, Latin-1, Latin Extended-A (pl, tr, ...), Cyrillic (ru, uk) and the punctuation the
interface writes (dashes, quotes, ellipsis, bullet, arrows, No); the others come from the u8g2 fonts.

Sources, downloaded once into upstream/fonts/inter (not in Git):
  https://github.com/rsms/inter/releases v4.1 (Inter-4.1.zip): extras/ttf/{Inter-Regular,Inter-Medium,
  Inter-SemiBold,Inter-Bold,InterDisplay-Medium}.ttf (OFL, i18n/fonts/inter/OFL.txt)
Needs Pillow and fontTools.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT/'upstream'/'fonts'/'inter'
INTER = 'v4.1'

TEXT = (list(range(0x20, 0x7f)) + list(range(0xa0, 0x180)) + list(range(0x400, 0x460)) + [0x490, 0x491]
        + list(range(0x2010, 0x2027)) + [0x2030, 0x2039, 0x203a, 0x20ac, 0x2116, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212])
DIGITS = [ord(c) for c in ' +,-./0123456789:%']

# name, TTF, cap height in px (the replaced face's 'H'; the digit face: its '0'), the face it replaces, code points,
# tracking: px added to each advance (the smallest face is too tight for the screen without it).
FONTS = [
    ('mmAaBody', 'Inter-Regular.ttf', 9, '6x13', TEXT, 0),
    ('mmAaBold', 'Inter-SemiBold.ttf', 9, '6x13B', TEXT, 0),
    ('mmAaSmall', 'Inter-Medium.ttf', 6, '5x8', TEXT, 0.6),
    ('mmAaBig', 'Inter-Medium.ttf', 13, '10x20', TEXT, 0),
    ('mmAaCard', 'Inter-Bold.ttf', 10, '9x15', TEXT, 0),
    ('mmAaDigits', 'InterDisplay-Medium.ttf', 42, 'logisoso42', DIGITS, 0),
]


def sized(path, cap, ch):
    """The smallest size (in 1/4 px steps) whose hinted cap height reaches cap."""
    size = cap
    while -ImageFont.truetype(str(path), size).getbbox(ch, anchor='ls')[1] < cap:
        size += 0.25
    return ImageFont.truetype(str(path), size), size


def render(font, cp, track):
    """Advance, bitmap width and height, left edge from the pen, top row above the baseline, coverage 0-15."""
    ch = chr(cp)
    adv = round(font.getlength(ch) + track)
    x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return adv, 0, 0, 0, 0, []
    img = Image.new('L', (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
    px = img.tobytes()
    rows = [r for r in range(h) if any(px[r*w:(r + 1)*w])]
    if not rows:
        return adv, 0, 0, 0, 0, []
    cols = [c for c in range(w) if any(px[r*w + c] for r in rows)]
    r0, r1, c0, c1 = rows[0], rows[-1] + 1, cols[0], cols[-1] + 1
    return adv, c1 - c0, r1 - r0, x0 + c0, -(y0 + r0), [(px[r*w + c]*15 + 127)//255 for r in range(r0, r1) for c in range(c0, c1)]


def face(name, ttf, cap, replaces, cps, track):
    path = SRC/ttf
    cmap = TTFont(path)['cmap'].getBestCmap()
    font, size = sized(path, cap, '0' if cps is DIGITS else 'H')
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for cp in sorted(c for c in set(cps) if c in cmap):
        adv, w, h, dx, top, cover = render(font, cp, track)
        cover += [0]*(len(cover) % 2)
        glyphs.append((cp, w, h, dx, top, adv, len(data)))
        data += bytes(cover[i] << 4 | cover[i + 1] for i in range(0, len(cover), 2))
    zero = next(g[5] for g in glyphs if g[0] == ord('0'))
    print(f'{name}: {ttf} at {size:g} px, {len(glyphs)} glyphs, {len(data)} bytes')
    return '\n'.join([
        f'// {ttf} at {size:g} px (cap height {cap} px, as {replaces}): {len(glyphs)} glyphs, {len(data)} bytes',
        f'static const uint8_t {name}Data[{max(1, len(data))}]={{' + ','.join(map(str, data or b'\0')) + '};',
        f'static const AaGlyph {name}Glyphs[{len(glyphs)}]={{' + ','.join('{' + ','.join(map(str, g)) + '}' for g in glyphs) + '};',
        f'static const AaFont {name}{{{name}Glyphs,{name}Data,{len(glyphs)},{ascent},{descent},{zero},{cap}}};'])


def generate():
    parts = [face(*f) for f in FONTS]
    head = ('// Anti-aliased faces of the 320x240 screens, generated by tools/i18n.py generate (tools/aa_fonts.py); do not edit.\n'
            '// Inter ' + INTER + ' (https://rsms.me/inter/), SIL Open Font License 1.1, i18n/fonts/inter/OFL.txt.\n'
            '#pragma once\n#include <stdint.h>\n'
            '// A glyph: its code point, the size of its bitmap, its left edge from the pen (dx), its top row above the\n'
            '// baseline (top), the pen advance and the offset of its 4-bit coverage in the face\'s data (rows of w pixels,\n'
            '// two to a byte, high nibble first, continuous across rows).\n'
            'struct AaGlyph{uint16_t cp;uint8_t w,h;int8_t dx,top;uint8_t advance;uint32_t offset;};\n'
            'struct AaFont{const AaGlyph* glyphs;const uint8_t* data;uint16_t count;uint8_t ascent,descent,zeroWidth,capHeight;};\n')
    (ROOT/'include'/'AaFonts.h').write_text(head + '\n'.join(parts) + '\n')
    print('include/AaFonts.h:', len(FONTS), 'faces')


if __name__ == '__main__':
    generate()
